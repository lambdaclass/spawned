//! Reproduce a fuzz input, shrink its decision tape and emit a regression.
//!
//! ```sh
//! cd fuzz
//! RUSTFLAGS="--cfg spawned_sim --cfg tokio_unstable" \
//!   cargo run --example repro -- artifacts/scenario/crash-<sha> [--emit <name>]
//! ```
//!
//! Prints the decoded scenario and the run's outcome. On failure it shrinks
//! the tape toward the canonical schedule (`SPAWNED_SIM_SHRINK` runs, default
//! 200) and, with `--emit <name>`, writes `regressions/<name>.input`,
//! `regressions/<name>.tape` and `tests/<name>.rs`, a test that replays the
//! minimized tape strictly and sweeps the scenario over simulator seeds.

use spawned_fuzz::{decode, execute, last_details, run_body, strategy};
use spawned_rt::tasks::sim;
use std::path::Path;

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let Some(input) = args.first() else {
        eprintln!("usage: repro <input> [--emit <name>]");
        std::process::exit(2);
    };
    let emit = args
        .iter()
        .position(|a| a == "--emit")
        .and_then(|i| args.get(i + 1))
        .cloned();
    let bytes = std::fs::read(input).expect("read input");
    let Some(scenario) = decode(&bytes) else {
        eprintln!("input does not decode to a scenario (too short)");
        std::process::exit(2);
    };
    println!("{scenario:#?}");
    println!("strategy {}, seed {}", strategy(scenario.sched), scenario.seed);
    let run = execute(&scenario, None);
    let Some(failure) = run.failure else {
        println!("PASS ({} polls)", run.polls);
        return;
    };
    println!("FAIL: {failure}");
    for detail in last_details() {
        println!("  {detail}");
    }
    let tape = run.tape.expect("a failing run records its tape");
    let strict = execute(&scenario, Some(&tape));
    println!(
        "strict tape replay: {}",
        strict.failure.as_deref().unwrap_or("passed (not reproducible!)")
    );
    let budget = std::env::var("SPAWNED_SIM_SHRINK")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(200);
    let body = |seed: u64| run_body(scenario.clone(), seed);
    let (small, runs) = sim::shrink(&tape, &failure, &body, budget);
    println!(
        "shrunk tape: {} -> {} decisions, {} -> {} deviations ({runs} runs)",
        tape.decisions.len(),
        small.decisions.len(),
        tape.deviations(),
        small.deviations()
    );
    let Some(name) = emit else {
        let path = std::env::temp_dir().join("spawned-fuzz/repro.min.tape");
        small.save(&path).expect("save tape");
        println!("minimized tape: {}", path.display());
        return;
    };
    assert!(
        name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'),
        "--emit takes an identifier"
    );
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    std::fs::create_dir_all(root.join("regressions")).unwrap();
    std::fs::create_dir_all(root.join("tests")).unwrap();
    std::fs::write(root.join(format!("regressions/{name}.input")), &bytes).unwrap();
    small
        .save(&root.join(format!("regressions/{name}.tape")))
        .unwrap();
    let scenario_doc: String = format!("{scenario:#?}")
        .lines()
        .map(|l| format!("//! {l}\n"))
        .collect();
    let test = format!(
        r#"//! Generated by `cargo run --example repro -- <input> --emit {name}`.
//!
//! Failure: {failure}
//! Strategy {strategy}, seed {seed}.
//!
//! ```text
{scenario_doc}//! ```
#![cfg(spawned_sim)]

const INPUT: &[u8] = include_bytes!("../regressions/{name}.input");
const TAPE: &str = include_str!("../regressions/{name}.tape");

/// The input under its own schedule and under the minimized failing tape.
#[test]
fn {name}_tape() {{
    spawned_fuzz::assert_passes(INPUT, Some(TAPE));
}}

/// The same operations under other simulator schedules.
#[spawned_macros::sim_test(seeds = 32)]
async fn {name}_seeds(seed: u64) {{
    spawned_fuzz::init();
    spawned_fuzz::run_body(spawned_fuzz::decode(INPUT).unwrap(), seed).await;
}}
"#,
        strategy = strategy(scenario.sched),
        seed = scenario.seed,
    );
    std::fs::write(root.join(format!("tests/{name}.rs")), test).unwrap();
    println!(
        "wrote regressions/{name}.input, regressions/{name}.tape, tests/{name}.rs\n\
         run: RUSTFLAGS=\"--cfg spawned_sim --cfg tokio_unstable\" cargo test --test {name}"
    );
}
